// Generates components/icons.generated.ts from Material Symbols (Outlined,
// weight 400): only the icons listed here are shipped, as inline SVG paths.
// Material Symbols are licensed under Apache 2.0 (Google).
// Run: node apps/lms/scripts/generate-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ICONS = {
  home: "home",
  learn: "school",
  library: "local_library",
  more: "more_horiz",
  done: "check_circle",
  notStarted: "radio_button_unchecked",
  inProgress: "pending",
  play: "play_circle",
  audio: "headphones",
  next: "arrow_forward",
  back: "arrow_back",
  outline: "toc",
  textSize: "format_size",
  note: "info",
  tip: "lightbulb",
  warning: "warning",
  correct: "check",
  wrong: "close",
  download: "download",
  print: "print",
  link: "open_in_new",
  document: "description",
  account: "account_circle",
  help: "help",
  logout: "logout",
  flag: "flag",
  timer: "timer",
  saved: "cloud_done",
  offline: "cloud_off",
  pause: "pause_circle",
  lock: "lock",
  assessment: "assignment",
  hide: "visibility_off",
};

const require = createRequire(import.meta.url);
const pkgDir = dirname(
  require.resolve("@material-symbols/svg-400/package.json"),
);
const out = {};
for (const [name, file] of Object.entries(ICONS)) {
  const svg = readFileSync(join(pkgDir, "outlined", `${file}.svg`), "utf8");
  const path = svg.match(/<path d="([^"]+)"/)?.[1];
  if (!path) throw new Error(`No path in ${file}.svg`);
  out[name] = path;
}
const here = dirname(fileURLToPath(import.meta.url));
const body = `// GENERATED by scripts/generate-icons.mjs, do not edit.
// Material Symbols Outlined (weight 400), Apache License 2.0, (c) Google.
// viewBox for every path: "0 -960 960 960".
export const ICON_PATHS = ${JSON.stringify(out, null, 2)} as const;

export type IconName = keyof typeof ICON_PATHS;
`;
writeFileSync(join(here, "..", "components", "icons.generated.ts"), body);
console.log(`Wrote ${Object.keys(out).length} icons.`);
