/**
 * Compile emails/standard.mjml into lib/server/emailTemplate.generated.ts.
 * Run after editing the .mjml: `yarn workspace lms email:template`.
 * MJML is a dev dependency only; the runtime uses the compiled HTML string.
 * test/emailTemplate.test.ts fails if the two drift apart.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import mjml2html from "mjml";

const root = path.join(__dirname, "..");
export const MJML_SOURCE = path.join(root, "emails", "standard.mjml");
export const GENERATED = path.join(root, "lib", "server", "emailTemplate.generated.ts");

export async function compileStandardEmail(): Promise<string> {
  // mjml 4 returns synchronously; the v5 type definitions say Promise. Await covers both.
  const { html, errors } = await mjml2html(readFileSync(MJML_SOURCE, "utf8"), {
    validationLevel: "strict",
    filePath: MJML_SOURCE,
  });
  if (errors.length) {
    throw new Error(errors.map((e) => e.formattedMessage).join("\n"));
  }
  return html;
}

export function generatedModule(html: string): string {
  return `// GENERATED by scripts/build-email-template.ts from emails/standard.mjml. Do not edit.
// Regenerate with: yarn workspace lms email:template

export const STANDARD_EMAIL_HTML = ${JSON.stringify(html)};
`;
}

if (require.main === module) {
  void compileStandardEmail().then((html) => {
    writeFileSync(GENERATED, generatedModule(html));
    console.info(`Wrote ${path.relative(root, GENERATED)}`);
  });
}
